//! A version dump: the bound classes of one Minecraft version and their
//! members, as committed under `mc-data/dumps/<version>.txt`.
//!
//! The text form is line-based and sorted, so the diff between two versions'
//! dumps reads as the list of what changed:
//!
//! ```text
//! version 26.3
//! jar-sha1 0123…
//! missing com/mojang/blaze3d/vulkan/VulkanDevice
//!
//! class net/minecraft/client/Camera public
//!   extends java/lang/Object
//!   field fov F private
//!   method position ()Lnet/minecraft/world/phys/Vec3; public
//! ```

use std::collections::{BTreeMap, BTreeSet};
use std::fmt::Write as _;

use crate::Error;

/// Access flags kept for a class, in the order they are written.
const CLASS_FLAGS: &[(u16, &str)] = &[
    (0x0001, "public"),
    (0x0010, "final"),
    (0x0200, "interface"),
    (0x0400, "abstract"),
    (0x2000, "annotation"),
    (0x4000, "enum"),
];
/// Access flags kept for a field.
const FIELD_FLAGS: &[(u16, &str)] = &[
    (0x0001, "public"),
    (0x0002, "private"),
    (0x0004, "protected"),
    (0x0008, "static"),
    (0x0010, "final"),
    (0x0040, "volatile"),
    (0x0080, "transient"),
    (0x4000, "enum"),
];
/// Access flags kept for a method.
const METHOD_FLAGS: &[(u16, &str)] = &[
    (0x0001, "public"),
    (0x0002, "private"),
    (0x0004, "protected"),
    (0x0008, "static"),
    (0x0010, "final"),
    (0x0020, "synchronized"),
    (0x0080, "varargs"),
    (0x0100, "native"),
    (0x0400, "abstract"),
];

/// Which flag table applies.
#[derive(Clone, Copy)]
pub enum Kind {
    Class,
    Field,
    Method,
}

impl Kind {
    fn table(self) -> &'static [(u16, &'static str)] {
        match self {
            Kind::Class => CLASS_FLAGS,
            Kind::Field => FIELD_FLAGS,
            Kind::Method => METHOD_FLAGS,
        }
    }

    /// `flags` reduced to the bits a dump records for this kind.
    pub fn keep(self, flags: u16) -> u16 {
        self.table()
            .iter()
            .filter(|(bit, _)| flags & bit != 0)
            .fold(0, |kept, (bit, _)| kept | bit)
    }
}

/// One field or method.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct Member {
    pub name: String,
    pub descriptor: String,
    pub flags: u16,
}

/// One class: its supertypes and members. Synthetic members (lambdas,
/// bridges, accessors) are not recorded.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Class {
    pub flags: u16,
    pub superclass: Option<String>,
    pub interfaces: Vec<String>,
    pub fields: BTreeSet<Member>,
    pub methods: BTreeSet<Member>,
}

/// Every bound class of one Minecraft version.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Dump {
    /// The version id, as `version.json` reports it.
    pub version: String,
    /// SHA-1 of the client jar the dump was read from.
    pub jar_sha1: String,
    /// Root classes that do not exist in this version.
    pub missing: BTreeSet<String>,
    pub classes: BTreeMap<String, Class>,
}

fn write_flags(out: &mut String, kind: Kind, flags: u16) {
    for (bit, word) in kind.table() {
        if flags & bit != 0 {
            out.push(' ');
            out.push_str(word);
        }
    }
}

fn parse_flags<'a>(
    kind: Kind,
    words: impl Iterator<Item = &'a str>,
    line: usize,
) -> Result<u16, Error> {
    let mut flags = 0;
    for word in words {
        let (bit, _) = kind
            .table()
            .iter()
            .find(|(_, name)| *name == word)
            .ok_or_else(|| Error::Parse {
                line,
                message: format!("unknown flag {word:?}"),
            })?;
        flags |= bit;
    }
    Ok(flags)
}

impl Dump {
    /// The committed text form.
    pub fn to_text(&self) -> String {
        let mut out = String::new();
        let _ = writeln!(
            out,
            "# Minecraft {}: the classes DarkClient binds, and their supertypes.",
            self.version
        );
        let _ = writeln!(
            out,
            "# Generated by `cargo xtask mc-dump {}`; do not edit by hand.",
            self.version
        );
        let _ = writeln!(out, "version {}", self.version);
        let _ = writeln!(out, "jar-sha1 {}", self.jar_sha1);
        for name in &self.missing {
            let _ = writeln!(out, "missing {name}");
        }
        for (name, class) in &self.classes {
            out.push('\n');
            out.push_str("class ");
            out.push_str(name);
            write_flags(&mut out, Kind::Class, class.flags);
            out.push('\n');
            if let Some(superclass) = &class.superclass {
                let _ = writeln!(out, "  extends {superclass}");
            }
            for interface in &class.interfaces {
                let _ = writeln!(out, "  implements {interface}");
            }
            for (keyword, kind, members) in [
                ("field", Kind::Field, &class.fields),
                ("method", Kind::Method, &class.methods),
            ] {
                for member in members {
                    let _ = write!(out, "  {keyword} {} {}", member.name, member.descriptor);
                    write_flags(&mut out, kind, member.flags);
                    out.push('\n');
                }
            }
        }
        out
    }

    /// Parses the text form back.
    pub fn parse(text: &str) -> Result<Dump, Error> {
        let mut dump = Dump::default();
        let mut current: Option<(String, Class)> = None;
        let error = |line: usize, message: String| Error::Parse { line, message };

        for (index, raw) in text.lines().enumerate() {
            let line = index + 1;
            let trimmed = raw.trim();
            if trimmed.is_empty() || trimmed.starts_with('#') {
                continue;
            }
            let mut words = trimmed.split_whitespace();
            let keyword = words.next().unwrap_or_default();
            let mut next = |what: &str| {
                words
                    .next()
                    .map(str::to_string)
                    .ok_or_else(|| error(line, format!("{keyword} without {what}")))
            };
            match keyword {
                "version" => dump.version = next("an id")?,
                "jar-sha1" => dump.jar_sha1 = next("a hash")?,
                "missing" => {
                    dump.missing.insert(next("a class")?);
                }
                "class" => {
                    let name = next("a name")?;
                    let class = Class {
                        flags: parse_flags(Kind::Class, words, line)?,
                        ..Class::default()
                    };
                    if let Some((done, class)) = current.replace((name, class)) {
                        dump.classes.insert(done, class);
                    }
                }
                "extends" | "implements" | "field" | "method" => {
                    let target = next("a name")?;
                    let (_, class) = current
                        .as_mut()
                        .ok_or_else(|| error(line, format!("{keyword} outside a class")))?;
                    match keyword {
                        "extends" => class.superclass = Some(target),
                        "implements" => class.interfaces.push(target),
                        _ => {
                            let descriptor = next("a descriptor")?;
                            let (kind, members) = if keyword == "field" {
                                (Kind::Field, &mut class.fields)
                            } else {
                                (Kind::Method, &mut class.methods)
                            };
                            members.insert(Member {
                                name: target,
                                descriptor,
                                flags: parse_flags(kind, words, line)?,
                            });
                        }
                    }
                }
                other => return Err(error(line, format!("unknown keyword {other:?}"))),
            }
        }
        if let Some((name, class)) = current {
            dump.classes.insert(name, class);
        }
        Ok(dump)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn sample() -> Dump {
        let mut camera = Class {
            flags: 0x0001,
            superclass: Some("java/lang/Object".into()),
            interfaces: vec!["net/minecraft/client/Thing".into()],
            ..Class::default()
        };
        camera.fields.insert(Member {
            name: "fov".into(),
            descriptor: "F".into(),
            flags: 0x0002,
        });
        camera.methods.insert(Member {
            name: "position".into(),
            descriptor: "()Lnet/minecraft/world/phys/Vec3;".into(),
            flags: 0x0001 | 0x0010,
        });
        let mut dump = Dump {
            version: "26.3".into(),
            jar_sha1: "abc123".into(),
            ..Dump::default()
        };
        dump.missing
            .insert("com/mojang/blaze3d/vulkan/VulkanDevice".into());
        dump.classes
            .insert("net/minecraft/client/Camera".into(), camera);
        dump.classes
            .insert("net/minecraft/client/Empty".into(), Class::default());
        dump
    }

    #[test]
    fn the_text_form_round_trips() {
        let dump = sample();
        assert_eq!(Dump::parse(&dump.to_text()).unwrap(), dump);
    }

    #[test]
    fn members_are_written_one_per_line_with_their_flags() {
        let text = sample().to_text();
        assert!(text.contains("\nclass net/minecraft/client/Camera public\n"));
        assert!(text.contains("\n  field fov F private\n"));
        assert!(
            text.contains("\n  method position ()Lnet/minecraft/world/phys/Vec3; public final\n")
        );
    }

    #[test]
    fn flags_outside_the_kind_are_dropped() {
        // ACC_SUPER and ACC_SYNTHETIC are never recorded for a class.
        assert_eq!(Kind::Class.keep(0x0001 | 0x0020 | 0x1000), 0x0001);
        // 0x0040 is `volatile` on a field but `bridge` on a method.
        assert_eq!(Kind::Field.keep(0x0040), 0x0040);
        assert_eq!(Kind::Method.keep(0x0040), 0);
    }

    #[test]
    fn malformed_lines_report_their_line_number() {
        let error = Dump::parse("version 26.3\n  field x I\n").unwrap_err();
        assert!(matches!(error, Error::Parse { line: 2, .. }));
        let error = Dump::parse("class A sometimes\n").unwrap_err();
        assert!(matches!(error, Error::Parse { line: 1, .. }));
    }
}
